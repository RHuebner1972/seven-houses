from typing import Annotated

from fastapi import APIRouter, Depends
from pydantic import BaseModel
from sqlalchemy.orm import Session

from app.auth.deps import current_user
from app.daily.service import (
    GENERATION_IN_PROGRESS,
    GENERATION_IN_PROGRESS_MESSAGE,
    find_daily,
    get_or_create_daily,
    is_in_progress,
    restart_daily,
)
from app.db import get_db
from app.errors import Conflict
from app.models import User
from app.ratelimit import DAILY_LIMIT, HOUR, check_user_rate
from app.readings.router import _stream, reading_payload

router = APIRouter()

DAILY_MAX_TOKENS = 600


class DailyBody(BaseModel):
    tz: str


@router.post("/daily")
def daily(
    body: DailyBody,
    user: Annotated[User, Depends(current_user)],
    db: Annotated[Session, Depends(get_db)],
):
    """Return today's completed card, or stream its generation.

    A pending daily touched within the stale window is being generated by another
    request: 409 generation_in_progress. A failed or stale-pending one is regenerated
    with the same card. Every generation (first or regeneration) counts toward the
    daily rate limit; returning a completed card does not.
    """
    reading = find_daily(db, user, body.tz)
    if reading is not None:
        if reading.status == "complete":
            return {"reading": reading_payload(reading)}
        if is_in_progress(reading):
            raise Conflict(GENERATION_IN_PROGRESS, GENERATION_IN_PROGRESS_MESSAGE)
    check_user_rate(db, user.id, "daily", DAILY_LIMIT, HOUR)
    if reading is None:
        reading, already_drawn = get_or_create_daily(db, user, body.tz)
        if already_drawn:  # lost a race with a concurrent first draw
            if reading.status == "complete":
                return {"reading": reading_payload(reading)}
            raise Conflict(GENERATION_IN_PROGRESS, GENERATION_IN_PROGRESS_MESSAGE)
    else:
        reading = restart_daily(db, reading)  # same card, no redraw, no debit (daily is free)
    return _stream(db, reading, cost=0, max_tokens=DAILY_MAX_TOKENS)
